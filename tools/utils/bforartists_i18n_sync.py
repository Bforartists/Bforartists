"""
Keep the Blender translations working for Bforartists' own English UI strings.

Blender looks translations up by their exact English text. Bforartists rewords many labels and
tooltips, and adds menus/operators of its own, so those strings show untranslated. The `.po`
files in `locale/po/` come from Blender's translators and are merged in weekly, so we never edit
their upstream lines. Instead every `.po` gets one BFA block appended at the end of the file,
between the markers below. Blender's `msgfmt` keeps the first entry of a msgid, so an upstream
translation always wins over ours once Blender has one.

The block is generated from the data in `tools/utils/bforartists_i18n/`:

- `bfa_messages.pot`  BFA-only English strings (no Blender translation exists for them).
                      Also the template for translators.
- `remap.po`          English lookup table: msgid = BFA text, msgstr = original Blender text.
                      Reuses the existing Blender translation of the original text.
- `new/<lang>.po`     Translations of BFA-only strings (machine made, marked for review,
                      or contributed by translators).

Some rewordings are recovered without a `remap.po` entry (see `rule_candidates()`).

Usage:
    python tools/utils/bforartists_i18n_sync.py extract --blender <path/to/bforartists.exe>
    python tools/utils/bforartists_i18n_sync.py write     # Rewrite the BFA block of every .po.
    python tools/utils/bforartists_i18n_sync.py check     # Report coverage and stale entries.
"""

__all__ = (
    "main",
)

import argparse
import glob
import os
import re
import subprocess
import sys
import tempfile

for stream in (sys.stdout, sys.stderr):
    try:
        stream.reconfigure(encoding="utf-8", errors="replace")
    except Exception:
        pass

ROOT_DIR = os.path.normpath(os.path.join(os.path.dirname(__file__), "..", ".."))
PO_DIR = os.path.join(ROOT_DIR, "locale", "po")
DATA_DIR = os.path.join(os.path.dirname(__file__), "bforartists_i18n")
BFA_POT = os.path.join(DATA_DIR, "bfa_messages.pot")
REMAP_PO = os.path.join(DATA_DIR, "remap.po")
NEW_DIR = os.path.join(DATA_DIR, "new")

BLOCK_START = "# BFA - Bforartists translations start."
BLOCK_END = "# BFA - Bforartists translations end."
# Written between the upstream text and the block, removed again when the block is rewritten.
BLOCK_SEPARATOR = "\n\n"
BLOCK_HEADER = (
    BLOCK_START + " Kept at the end of the file so the weekly Blender merges stay conflict free.\n"
    "# BFA - Generated by tools/utils/bforartists_i18n_sync.py, don't edit by hand.\n"
    "# BFA - On a merge conflict here keep both sides: upstream entries first, this block last.\n"
)

DEFAULT_CTXT = ""
COMMENT_MACHINE = "# BFA - machine translated, please review"

# Contexts the extractor stores as "default", see `BLT_is_default_context()`.
_DEFAULT_CTXTS = {"", "*"}


# -----------------------------------------------------------------------------
# Minimal PO reading/writing.
# Mirrors what `source/blender/blentranslation/msgfmt/msgfmt.cc` understands.

_ESCAPES = {"n": "\n", "t": "\t", "\\": "\\", "\"": "\"", "r": "\r"}


def _unquote(s):
    s = s.strip()
    assert s[0] == '"' and s[-1] == '"', s
    s = s[1:-1]
    return re.sub(r'\\(.)', lambda m: _ESCAPES.get(m.group(1), "\\" + m.group(1)), s)


def _quote(s):
    return '"' + s.replace("\\", "\\\\").replace('"', '\\"').replace("\n", "\\n").replace("\t", "\\t") + '"'


def po_parse(text):
    """
    Parse PO text into a list of entries ``(comments, ctxt, msgid, msgstr, is_fuzzy)``.
    The header entry (empty msgid) is skipped.
    """
    entries = []
    comments = []
    cur = None
    field = None

    def flush():
        nonlocal cur
        if cur is not None and cur["msgid"]:
            entries.append((cur["comments"], cur["ctxt"], cur["msgid"], cur["msgstr"], cur["fuzzy"]))
        cur = None

    def new_entry():
        nonlocal comments
        entry = {"comments": comments, "ctxt": DEFAULT_CTXT, "msgid": "", "msgstr": "", "fuzzy": False}
        entry["fuzzy"] = any(c.startswith("#,") and "fuzzy" in c for c in comments)
        comments = []
        return entry

    for line in text.splitlines():
        if not line.strip():
            continue
        if line.startswith("#"):
            if cur is not None and field == "msgstr":
                flush()
            comments.append(line)
            continue
        if line.startswith("msgctxt "):
            flush()
            cur = new_entry()
            field = "ctxt"
            cur["ctxt"] = _unquote(line[8:])
        elif line.startswith("msgid_plural"):
            # Plural forms are not used by Blender's UI translations.
            field = None
        elif line.startswith("msgid "):
            if cur is None or field != "ctxt":
                flush()
                cur = new_entry()
            field = "msgid"
            cur["msgid"] = _unquote(line[6:])
        elif line.startswith("msgstr"):
            field = "msgstr"
            cur["msgstr"] = _unquote(line.split(" ", 1)[1])
        elif line.startswith('"') and cur is not None and field:
            cur[field] += _unquote(line)
    flush()
    return entries


def po_entry(ctxt, msgid, msgstr, comments=()):
    lines = list(comments)
    if ctxt not in _DEFAULT_CTXTS:
        lines.append("msgctxt " + _quote(ctxt))
    lines.append("msgid " + _quote(msgid))
    lines.append("msgstr " + _quote(msgstr))
    return "\n".join(lines) + "\n"


def norm_ctxt(ctxt):
    return DEFAULT_CTXT if ctxt in _DEFAULT_CTXTS else ctxt


def split_block(text):
    """Return ``(upstream_text, bfa_block_text)`` of a `.po` file."""
    i = text.find(BLOCK_START)
    if i == -1:
        return text, ""
    j = text.find(BLOCK_END, i)
    end = len(text) if j == -1 else j + len(BLOCK_END)
    upstream = text[:i]
    if upstream.endswith(BLOCK_SEPARATOR):
        upstream = upstream[:-len(BLOCK_SEPARATOR)]
    return upstream, text[i:end]


def read_text(path):
    with open(path, encoding="utf-8") as fh:
        return fh.read()


def write_text(path, text):
    # Keep the line endings the file already has (CRLF in Windows checkouts).
    newline = "\n"
    if os.path.exists(path):
        with open(path, "rb") as fh:
            if b"\r\n" in fh.read(4096):
                newline = "\r\n"
    with open(path, "w", encoding="utf-8", newline=newline) as fh:
        fh.write(text)


def translations(entries):
    """``{(ctxt, msgid): msgstr}`` of translated, non fuzzy entries (first one wins, like msgfmt)."""
    result = {}
    for _comments, ctxt, msgid, msgstr, fuzzy in entries:
        if msgstr and not fuzzy:
            result.setdefault((norm_ctxt(ctxt), msgid), msgstr)
    return result


def load_po_dir():
    """``{lang: (path, upstream_text, {(ctxt, msgid): msgstr})}`` for all `locale/po` files."""
    result = {}
    for path in sorted(glob.glob(os.path.join(PO_DIR, "*.po"))):
        lang = os.path.splitext(os.path.basename(path))[0]
        upstream, _block = split_block(read_text(path))
        result[lang] = (path, upstream, translations(po_parse(upstream)))
    return result


def load_data_po(path):
    return po_parse(read_text(path)) if os.path.exists(path) else []


# -----------------------------------------------------------------------------
# Matching BFA strings to Blender ones.

def rule_candidates(ctxt, msgid):
    """
    Yield ``(ctxt, blender_msgid, fix_translation)`` guesses for systematic BFA rewordings.
    ``fix_translation`` adjusts the Blender translation for the BFA text, ``None`` means unchanged.
    """
    # "data-block" was renamed to "data" in many BFA tooltips.
    if "data" in msgid:
        yield ctxt, re.sub(r"\bdata\b", "data-block", msgid), None
        yield ctxt, re.sub(r"\bdata\b", "data-block", msgid, count=1), None
    # BFA dropped the trailing "..." of menu entries opening a dialog.
    yield ctxt, msgid + "...", lambda s: s[:-3] if s.endswith("...") else s.rstrip("…")
    # "Blender" was renamed to "Bforartists".
    if "Bforartists" in msgid:
        yield ctxt, msgid.replace("Bforartists", "Blender"), lambda s: s.replace("Blender", "Bforartists")


def find_translation(ctxt, msgid, trans):
    """Translation of a BFA string reusing Blender's translations, or ``None``."""
    for c_ctxt, c_msgid, fix in rule_candidates(ctxt, msgid):
        msgstr = trans.get((c_ctxt, c_msgid))
        if msgstr:
            msgstr = fix(msgstr) if fix else msgstr
            if fix and "Bforartists" in msgid and "Bforartists" not in msgstr:
                continue
            return msgstr
    # BFA operator tooltips put the operator name as a title line before the description
    # (`"Title\nDescription"`). Translate both parts when Blender has them.
    if "\n" in msgid:
        title, desc = msgid.split("\n", 1)
        t_title = (trans.get((ctxt, title)) or trans.get(("Operator", title)) or
                   find_translation(ctxt, title, trans))
        t_desc = trans.get((ctxt, desc)) or find_translation(ctxt, desc, trans)
        if t_title and t_desc:
            return t_title + "\n" + t_desc
    return None


def remap_lookup(ctxt, blender_msgid, trans):
    """Translation of a `remap.po` Blender text, which may live in another context than the BFA text."""
    return (trans.get((ctxt, blender_msgid)) or trans.get((DEFAULT_CTXT, blender_msgid)) or
            trans.get(("Operator", blender_msgid)) or find_translation(ctxt, blender_msgid, trans))


# -----------------------------------------------------------------------------
# Commands.

def cmd_extract(args):
    """Extract all UI messages from a Bforartists build and store the BFA-only ones."""
    if args.pot:
        pot_path = args.pot
    else:
        pot_path = _run_extraction(args)
        if not pot_path:
            return 1

    pos = load_po_dir()
    known = set()
    for _path, _upstream, trans in pos.values():
        known.update(trans)

    blender_src = _blender_literals(args.blender_ref)
    out = []
    for comments, ctxt, msgid, _msgstr, _fuzzy in po_parse(read_text(pot_path)):
        key = (norm_ctxt(ctxt), msgid)
        if key in known:
            continue
        # Strings that also exist in Blender are translated by Blender's community, skip them.
        if _in_blender(msgid, blender_src):
            continue
        out.append(po_entry(ctxt, msgid, "", [c for c in comments if c.startswith("#:")][:3]))

    os.makedirs(DATA_DIR, exist_ok=True)
    write_text(BFA_POT, _pot_header() + "\n\n".join(out))
    print("Wrote {} BFA-only messages to {}".format(len(out), BFA_POT))
    return 0


def _run_extraction(args):
    work = tempfile.mkdtemp(prefix="bfa_i18n_")
    pot_path = os.path.join(work, "bforartists.pot")
    settings = '{{"SOURCE_DIR": "{}", "I18N_DIR": "{}"}}'.format(
        ROOT_DIR.replace("\\", "/"), work.replace("\\", "/"))
    script = os.path.join(ROOT_DIR, "scripts", "modules", "_bl_i18n_utils", "bl_extract_messages.py")
    if args.extract_script:
        script = args.extract_script
    cmd = [args.blender, "--background", "--factory-startup", "--python", script,
           "--", "-c", "-o", pot_path, "-s", settings]
    print("Running:", " ".join(cmd))
    subprocess.run(cmd, check=False)
    if not os.path.exists(pot_path):
        print("Extraction failed, no POT written.")
        return None
    return pot_path


def _probe(msgid):
    chunk = re.split(r'[\n"\\{}%]', msgid)[0][:60]
    return chunk if len(chunk) >= 3 else None


def _blender_literals(ref):
    """All string literal text of Blender's own UI code, joined, for substring tests."""
    files = subprocess.run(
        ["git", "ls-tree", "-r", "--name-only", ref, "--", "source", "scripts", "intern", "release/datafiles"],
        capture_output=True, text=True, cwd=ROOT_DIR, check=True).stdout.split()
    files = [f for f in files if f.endswith((".c", ".cc", ".cpp", ".h", ".hh", ".py", ".osl", ".glsl"))]
    chunks = []
    batch = 400
    for i in range(0, len(files), batch):
        # `git cat-file --batch` streams many blobs quickly.
        names = "".join("{}:{}\n".format(ref, f) for f in files[i:i + batch])
        data = subprocess.run(["git", "cat-file", "--batch"], input=names.encode(),
                              capture_output=True, cwd=ROOT_DIR, check=True).stdout
        chunks.append(data.decode("utf-8", "replace"))
    return "\n".join(chunks)


def _in_blender(msgid, blender_src):
    if not re.search(r'[\n"\\{}%]', msgid):
        # Plain strings must match a whole literal (also catches the start of a split C string).
        return ('"' + msgid + '"') in blender_src
    probe = _probe(msgid)
    return bool(probe) and ('"' + probe) in blender_src


def _pot_header():
    return (
        "# Bforartists-only UI messages, no Blender translation exists for them.\n"
        "# Generated by tools/utils/bforartists_i18n_sync.py extract.\n"
        "# Translations go to tools/utils/bforartists_i18n/new/<lang>.po\n"
        "msgid \"\"\n"
        "msgstr \"\"\n"
        "\"Content-Type: text/plain; charset=UTF-8\\n\"\n\n"
    )


def build_block(lang, trans, bfa_msgs, remap, new):
    """Return the BFA block text for one language and its entry count."""
    out = []
    done = set()

    def add(ctxt, msgid, msgstr, comments):
        key = (norm_ctxt(ctxt), msgid)
        # Never duplicate a msgid Blender translates already, its translation wins anyway.
        if key in trans or key in done or not msgstr:
            return
        done.add(key)
        out.append(po_entry(ctxt, msgid, msgstr, comments))

    # 1. Translations of BFA strings (contributed or machine made).
    for comments, ctxt, msgid, msgstr, fuzzy in new:
        if not fuzzy:
            add(ctxt, msgid, msgstr, [c for c in comments if c.startswith("# BFA")] or [COMMENT_MACHINE])

    # 2. Explicit English remaps, reusing Blender's translation of the original text.
    for _comments, ctxt, msgid, blender_msgid, _fuzzy in remap:
        ctxt = norm_ctxt(ctxt)
        msgstr = remap_lookup(ctxt, blender_msgid, trans)
        if msgstr and "Bforartists" in msgid and "Bforartists" not in blender_msgid:
            msgstr = msgstr.replace("Blender", "Bforartists")
        # Keep a suffix BFA appended, e.g. "Pose Breakdowner (Legacy)".
        suffix = msgid[len(blender_msgid):] if msgid.startswith(blender_msgid) else ""
        if msgstr and re.fullmatch(r" \([^()]+\)", suffix):
            msgstr += suffix
        # Keep the leading spaces BFA uses to indent some labels.
        indent = msgid[:len(msgid) - len(msgid.lstrip(" "))]
        if msgstr and indent and not blender_msgid.startswith(" "):
            msgstr = indent + msgstr
        add(ctxt, msgid, msgstr, ["# BFA - remap of " + _quote(blender_msgid)])

    # 3. Systematic rewordings, found by rules.
    for _comments, ctxt, msgid, _msgstr, _fuzzy in bfa_msgs:
        ctxt = norm_ctxt(ctxt)
        if (ctxt, msgid) not in done:
            add(ctxt, msgid, find_translation(ctxt, msgid, trans), ["# BFA - reworded Blender string"])

    if not out:
        return "", 0
    return BLOCK_HEADER + "\n\n" + "\n\n".join(out) + "\n\n" + BLOCK_END + "\n", len(out)


def cmd_write(args):
    bfa_msgs = load_data_po(BFA_POT)
    remap = load_data_po(REMAP_PO)
    total = 0
    for lang, (path, upstream, trans) in load_po_dir().items():
        if args.lang and lang not in args.lang:
            continue
        new = load_data_po(os.path.join(NEW_DIR, lang + ".po"))
        block, count = build_block(lang, trans, bfa_msgs, remap, new)
        # The upstream part stays byte for byte as Blender ships it.
        text = upstream + (BLOCK_SEPARATOR + block if block else "")
        if text != read_text(path):
            write_text(path, text)
        print("{:10} {:6} BFA entries".format(lang, count))
        total += count
    print("Total:", total)
    return 0


def cmd_check(args):
    bfa_msgs = load_data_po(BFA_POT)
    remap = load_data_po(REMAP_PO)
    pos = load_po_dir()
    known = {}
    for _path, _upstream, trans in pos.values():
        known.update(trans)

    stale = [m for _c, ctxt, m, blender_msgid, _f in remap
             if not remap_lookup(norm_ctxt(ctxt), blender_msgid, known)]
    print("remap.po entries whose Blender text no longer exists upstream: {}".format(len(stale)))
    for m in stale[:args.limit]:
        print("    " + _quote(m))

    upstream_now = [m for _c, ctxt, m, _s, _f in bfa_msgs if (norm_ctxt(ctxt), m) in known]
    print("bfa_messages.pot entries Blender now translates itself (re-run extract): {}".format(len(upstream_now)))

    print("\nBFA-only messages still untranslated, per language:")
    for lang, (path, _upstream, trans) in pos.items():
        if args.lang and lang not in args.lang:
            continue
        block = translations(po_parse(split_block(read_text(path))[1]))
        missing = sum(1 for _c, ctxt, m, _s, _f in bfa_msgs if (norm_ctxt(ctxt), m) not in block)
        print("    {:10} {:5} of {}".format(lang, missing, len(bfa_msgs)))
    return 0


def main():
    parser = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    sub = parser.add_subparsers(dest="command", required=True)

    p = sub.add_parser("extract", help="Extract BFA-only messages from a Bforartists build.")
    p.add_argument("--blender", help="Path to the Bforartists executable.")
    p.add_argument("--pot", help="Use an already extracted POT instead of running Bforartists.")
    p.add_argument("--blender-ref", default="blender/main", help="Git ref of pure Blender.")
    p.add_argument("--extract-script", default=None, help="Alternative bl_extract_messages.py.")
    p.set_defaults(func=cmd_extract)

    p = sub.add_parser("write", help="Rewrite the BFA block at the end of every locale/po file.")
    p.add_argument("--lang", nargs="*", help="Only these languages.")
    p.set_defaults(func=cmd_write)

    p = sub.add_parser("check", help="Report coverage and stale entries.")
    p.add_argument("--lang", nargs="*", help="Only these languages.")
    p.add_argument("--limit", type=int, default=20, help="Max listed items.")
    p.set_defaults(func=cmd_check)

    args = parser.parse_args()
    return args.func(args)


if __name__ == "__main__":
    sys.exit(main())
